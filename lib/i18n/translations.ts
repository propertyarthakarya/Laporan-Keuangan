// Struktur 'en' dijadikan acuan tipe (source of truth), jadi kalau kamu
// tambah key baru di 'en' tapi lupa di 'id', TypeScript akan kasih error.
export type TranslationSchema = typeof translations.en;

// Bikin union semua path key ber-titik, contoh: 'nav.dashboard' | 'common.save' | ...
type DotNestedKeys<T> = T extends string
  ? never
  : {
      [K in keyof T & string]: T[K] extends string ? K : `${K}.${DotNestedKeys<T[K]>}`;
    }[keyof T & string];

export type TranslationKey = DotNestedKeys<TranslationSchema>;